def test_project_gate_rejects_a_manual_plugin_map_edit(tmp_path: Path) -> None:
    project = _project(tmp_path, "Alpha")
    _catalog(tmp_path, "NF's Plugins-Filter/Alpha.json")
    _solution(tmp_path, [project])
    plan = build_classification_plan(tmp_path)
    apply_classification_plan(plan)
    check_project_classification(tmp_path, project)

    plan.plugin_map_path.write_text(
        plan.plugin_map_text.replace("NF's Plugins-Filter", "NF's Plugins-Cell"),
        encoding="utf-8",
    )
    with pytest.raises(ClassificationError, match="PluginMap is stale"):
        check_project_classification(tmp_path, project)
