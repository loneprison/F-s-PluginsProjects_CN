@dataclass(frozen=True)
class UiText:
    locale: UiLocale

    def text(self, key: str, **values: object) -> str:
        return _MESSAGES[self.locale][key].format(**values)

    def stage_label(self, stage: WorkflowStage) -> str:
        return stage.labels.get(self.locale, stage.labels["en"])

    def popup_issue(self, issue: PopupStructureIssue) -> str:
        return self.text(
            f"popup.issue.{issue.kind}",
            expected=issue.expected_count,
            actual=issue.actual_count,
            index=issue.index,
        )

    def diagnostic(self, diagnostic: Mapping[str, object]) -> str:
        code = str(diagnostic.get("code") or "")
        key = f"diagnostic.{code}"
        if key not in _EN:
            return str(diagnostic.get("message") or "")
        arguments = diagnostic.get("arguments")
        values = dict(arguments) if isinstance(arguments, Mapping) else {}
        try:
            return self.text(key, **values)
        except (KeyError, ValueError):
            return str(diagnostic.get("message") or "")


def ag_grid_locale_text(text: UiText) -> dict[str, str]:
    return dict(_AG_GRID_LOCALE_TEXT[text.locale])


def normalize_ui_locale(value: object) -> UiLocale:
    return value if value in SUPPORTED_UI_LOCALES else DEFAULT_UI_LOCALE  # type: ignore[return-value]
